#!/usr/bin/env python3
"""Write assets/js/order-strings.js (texts of the public order page /o/, TICKET-047).

The texts are the designer's: id -> Arabic / English rows of `docs/design/_build/web_copy.py` in the
main Abaya repository (the website repository sits in its `website/` folder). The ids are kept as they
are; the page (assets/js/order.js) and tools/build.py use them. Run after the designer changes the
copy, then `python tools/build.py`:

    python website/tools/gen_order_strings.py [path/to/web_copy.py]

Python 3.8+, standard library only. The output is `window.ORDER_STRINGS = <JSON>;` so build.py and
the Node test can read it as JSON.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT.parent / "docs" / "design" / "_build" / "web_copy.py"
OUT = ROOT / "assets" / "js" / "order-strings.js"
PREFIX = "window.ORDER_STRINGS = "


def load_rows(source):
    scope = {"__file__": str(source)}
    exec(compile(source.read_text(encoding="utf-8"), str(source), "exec"), scope)
    rows = []
    for _title, _note, group in scope["GROUPS"]:
        rows.extend(group)
    return rows


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SOURCE
    rows = load_rows(source)
    strings = {"ar": {}, "en": {}}
    for row in rows:
        sid, ar, en = row[0], row[1], row[2]
        if sid in strings["ar"]:
            raise SystemExit(f"duplicate id {sid}")
        strings["ar"][sid] = ar
        strings["en"][sid] = en
    body = json.dumps(strings, ensure_ascii=False, indent=1)
    OUT.write_text(
        "/* Texts of the public order page (/o/), ids as in docs/design/copy-online-order-page.md.\n"
        "   Generated by tools/gen_order_strings.py from docs/design/_build/web_copy.py; do not edit. */\n"
        + PREFIX + body + ";\n",
        encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} ids)")


if __name__ == "__main__":
    main()
